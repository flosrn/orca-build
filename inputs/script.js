import { createHash as createHash2 } from "crypto";
function isTable(value) {
  if (value === null || typeof value !== "object" || Array.isArray(value))
    return false;
  const prototype = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}
function nonemptyString(value) {
  return typeof value === "string" && value.trim().length > 0;
}
function canonicalJSON(value, fail) {
  if (value === null || typeof value === "string" || typeof value === "boolean")
    return JSON.stringify(value);
  if (typeof value === "number" && Number.isFinite(value))
    return JSON.stringify(value);
  if (Array.isArray(value))
    return `[${value.map((item) => canonicalJSON(item, fail)).join(",")}]`;
  if (isTable(value))
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonicalJSON(value[key], fail)}`).join(",")}}`;
  return fail("selected lock metadata must be JSON-compatible");
}
function buildDigest(manifest, lock) {
  const parsed = Bun.TOML.parse(new TextDecoder("utf-8", { fatal: true }).decode(manifest));
  if (!isTable(parsed))
    throw new Error("build.toml must be a table");
  const platforms = parsed.platforms;
  if (platforms !== undefined && !isTable(platforms))
    throw new Error("build.toml platforms must be a table");
  const tools = isTable(lock) && isTable(lock.tools) ? lock.tools : undefined;
  const selected = [];
  for (const platform of Object.keys(platforms ?? {}).sort()) {
    const declaration = platforms[platform];
    if (!isTable(declaration))
      throw new Error(`build.toml platform ${platform} must be a table`);
    const toolchain = declaration.toolchain;
    if (toolchain === undefined)
      continue;
    if (!isTable(toolchain))
      throw new Error(`build.toml platform ${platform} toolchain must be a table`);
    for (const tool of Object.keys(toolchain).sort()) {
      const version = toolchain[tool];
      const fail = (detail) => {
        throw new Error(`build digest ${platform}/${tool}@${String(version)}: ${detail}`);
      };
      if (!nonemptyString(version))
        fail("manifest tool version must be a nonempty string");
      const entries = tools && Object.hasOwn(tools, tool) ? tools[tool] : undefined;
      const matches = Array.isArray(entries) ? entries.filter((entry) => isTable(entry) && entry.version === version) : [];
      if (matches.length !== 1)
        fail(matches.length === 0 ? "required lock tool version is absent" : "required lock tool version is ambiguous");
      const entry = matches[0];
      const key = `platforms.${platform}`;
      const artifact = Object.hasOwn(entry, key) ? entry[key] : undefined;
      if (!isTable(artifact))
        fail("required lock platform artifact is absent or invalid");
      if (!nonemptyString(entry.backend))
        fail("lock backend must be a nonempty string");
      if (!Array.isArray(entry.specifiers) || entry.specifiers.length === 0 || !entry.specifiers.every(nonemptyString))
        fail("lock specifiers must be a nonempty array of nonempty strings");
      if (typeof artifact.checksum !== "string" || !/^sha256:[0-9a-f]{64}$/.test(artifact.checksum))
        fail("lock platform checksum must be sha256:<64 lowercase hex digits>");
      if (!nonemptyString(artifact.url))
        fail("lock platform url must be a nonempty HTTP(S) URL");
      try {
        const url = new URL(artifact.url);
        if (url.protocol !== "https:" && url.protocol !== "http:")
          fail("lock platform url must be an HTTP(S) URL");
      } catch {
        fail("lock platform url must be an HTTP(S) URL");
      }
      selected.push(canonicalJSON({ platform, tool, version, backend: entry.backend, specifiers: entry.specifiers, artifact }, fail));
    }
  }
  return createHash2("sha256").update(manifest).update("\x00").update(`[${selected.join(",")}]`).digest("hex");
}

