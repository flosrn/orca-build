function readSeries(seriesDir) {
  const orderPath = join(seriesDir, ".patches");
  if (!existsSync2(orderPath)) {
    if (existsSync2(seriesDir) && readdirSync(seriesDir).some((name) => name.endsWith(".patch")))
      throw new SeriesError("invalid-series", "patch files exist without .patches");
    return { order: Buffer.alloc(0), patches: [] };
  }
  if (!lstatSync(orderPath).isFile())
    throw new SeriesError("invalid-series", ".patches must be a regular file");
  const order = readFileSync(orderPath), text = order.toString("utf8");
  const names = text === "" ? [] : text.endsWith(`
`) ? text.slice(0, -1).split(`
`) : [];
  const listed = new Set(names);
  if (text && !text.endsWith(`
`) || names.some((name) => !PATCH_NAME.test(name)) || listed.size !== names.length)
    throw new SeriesError("invalid-series", ".patches must contain unique, safe .patch filenames, one per LF-terminated line");
  const patches = names.map((name) => {
    const path = join(seriesDir, name);
    if (!existsSync2(path) || !lstatSync(path).isFile())
      throw new SeriesError("invalid-series", `${name} is missing or is not a regular file`);
    return { name, bytes: readFileSync(path) };
  });
  const unlisted = readdirSync(seriesDir).filter((name) => name.endsWith(".patch") && !listed.has(name));
  if (unlisted.length)
    throw new SeriesError("invalid-series", `unlisted patches: ${unlisted.join(", ")}`);
  return { order, patches };
}
function seriesDigest(seriesDir) {
  const series = readSeries(seriesDir), hash = createHash("sha256").update(series.order);
  for (const patch of series.patches)
    hash.update(patch.bytes);
  return hash.digest("hex");
}
async function importSeries(options, deps = {}) {
  const { mirror, tag } = options, workDir = resolve2(options.workDir), seriesDir = resolve2(options.seriesDir);
  const series = readSeries(seriesDir), git = new GitClient(deps);
  await assertFullMirror(mirror, deps);
  const base = await commitOf(git, mirror, `refs/tags/${tag}`);
  if (existsSync2(workDir))
    throw new Error(`workbench already exists: ${workDir}`);
  const quoted = (value) => `'${value.replaceAll("'", "'\\''")}'`;
  await git.text(mirror, ["clone", "--shared", "--no-checkout", "--template=", `--upload-pack=${quoted(git.executable)} -c safe.directory=${quoted(resolve2(mirror))} upload-pack`, "--", resolve2(mirror), workDir]);
  await git.text(workDir, ["checkout", "--detach", base]);
  let head = base;
  for (const patch of series.patches) {
    const r = await git.run(workDir, ["-c", "am.messageid=false", "-c", "am.keepcr=true", "am", "-3", "--keep-cr", "--keep", "--no-scissors", "--whitespace=nowarn", "--", join(seriesDir, patch.name)], COMMITTER);
    const next = await git.text(workDir, ["rev-parse", "HEAD"]), detail = `${r.stdout}${r.stderr}`.trim();
    if (r.code !== 0)
      return { status: /Patch is empty/.test(detail) ? "empty" : "conflict", head: next, patch: patch.name, detail };
    if (next === head)
      return { status: "empty", head, patch: patch.name, detail };
    head = next;
  }
  return { status: "applied", head };
}
