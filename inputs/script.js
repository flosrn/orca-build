import { createHash as createHash4 } from "crypto";
var SCRIPT = "script.js";
var RECEIPT = "receipt.json";
var sha2562 = (bytes) => createHash4("sha256").update(bytes).digest("hex");
function hostedSnapshot(manifest, lock, script) {
  return `${JSON.stringify({ manifest: sha2562(manifest), lock: sha2562(lock), script: sha2562(script) })}
`;
}

// components/orca/runner/script.ts
var PLATFORM = "macos-arm64";
var SYSTEM_PATH = ["/usr/bin", "/bin", "/usr/sbin", "/sbin"];
async function installMise(lock, directory) {
  const entries = lock?.tools?.["github:jdx/mise"];
  const pinned = Array.isArray(entries) && entries.length === 1 ? entries[0][`platforms.${PLATFORM}`] : undefined;
  if (typeof pinned?.url !== "string" || !pinned.url.startsWith("https://") || typeof pinned.checksum !== "string" || !/^sha256:[0-9a-f]{64}$/.test(pinned.checksum))
    throw new Error("unverified/build-wrapper: mise.lock pins no single mise for macos-arm64");
  const response = await fetch(pinned.url, { signal: AbortSignal.timeout(300000) });
  if (!response.ok)
    throw new Error(`unverified/network: mise download: HTTP ${response.status}`);
  const archive = Buffer.from(await response.arrayBuffer());
  if (`sha256:${sha256(archive)}` !== pinned.checksum)
    throw new Error("unverified/snapshot-mismatch: the mise download differs from mise.lock");
  const tar = pinned.url.endsWith(".tar.zst") ? zstdDecompressSync(archive) : pinned.url.endsWith(".tar.gz") ? gunzipSync(archive) : undefined;
  if (!tar)
    throw new Error(`unverified/build-wrapper: unsupported mise archive ${basename2(pinned.url)}`);
  mkdirSync3(directory, { recursive: true });
  writeFileSync3(join3(directory, "mise.tar"), tar);
  const extracted = Bun.spawnSync(["tar", "-xf", join3(directory, "mise.tar"), "-C", directory], { stdout: "ignore", stderr: "pipe" });
  if (extracted.exitCode !== 0)
    throw new Error(`unverified/build-wrapper: mise archive: ${extracted.stderr.toString().trim()}`);
  const find = (dir) => {
    for (const name of readdirSync2(dir)) {
      const path = join3(dir, name);
      if (statSync2(path).isDirectory()) {
        const found = find(path);
        if (found)
          return found;
      } else if (name === "mise" && basename2(dir) === "bin")
        return path;
    }
  };
  const executable = find(directory);
  if (!executable)
    throw new Error("unverified/build-wrapper: the mise archive holds no bin/mise");
  return executable;
}
async function runHosted(options) {
  const { component, upstreamTag, upstreamCommit, series, build } = options;
  const inputs = resolve5(options.inputs), out = resolve5(options.out), work = resolve5(options.work);
  mkdirSync3(out, { recursive: true });
  mkdirSync3(work, { recursive: true });
  const finish = (result) => {
    const artifacts = result.verdict === "ok" ? result.artifacts : [];
    for (const artifact of artifacts)
      copyFileSync2(artifact.path, join3(out, basename2(artifact.path)));
    const receipt = { component, platform: PLATFORM, upstreamTag, upstreamCommit, series, build, result: { ...result, artifacts: artifacts.map((artifact) => ({ ...artifact, path: basename2(artifact.path) })) } };
    writeFileSync3(join3(out, RECEIPT), `${JSON.stringify(receipt, null, 2)}
`);
    return result.verdict === "ok" ? 0 : 1;
  };
  const refuse = (verdict, reason, detail) => finish({ verdict, reason, detail, artifacts: [], qualification: "hosted" });
  if (!/^[a-z0-9][a-z0-9-]*$/.test(component) || !/^[A-Za-z0-9._+-]+$/.test(upstreamTag) || !/^[0-9a-f]{40}$/.test(upstreamCommit) || !/^[0-9a-f]{64}$/.test(series) || !/^[0-9a-f]{64}$/.test(build)) {
    return refuse("unverified", "build-wrapper", "the dispatch inputs are malformed");
  }
  try {
    const manifest = readFileSync3(join3(inputs, "build.toml")), lockBytes = readFileSync3(join3(inputs, "mise.lock")), script = readFileSync3(join3(inputs, SCRIPT));
    const lock = Bun.TOML.parse(lockBytes.toString("utf8"));
    const { manifest: declared } = parseBuildManifest(manifest, lock);
    const snapshot = join3(work, "snapshot.json");
    writeFileSync3(snapshot, hostedSnapshot(manifest, lockBytes, script));
    const home = join3(work, "home");
    mkdirSync3(home, { recursive: true });
    const git = { env: { PATH: process.env.PATH, HOME: home } };
    const mirror = join3(work, "upstream.git");
    await createMirror({ upstream: options.upstream ?? `https://github.com/${declared.upstream.repository}.git`, mirror }, git);
    const tagged = await new GitClient(git).run(mirror, ["rev-parse", "--verify", "--end-of-options", `refs/tags/${upstreamTag}^{commit}`]);
    if (tagged.code !== 0 || tagged.stdout.trim() !== upstreamCommit)
      return refuse("unverified", "upstream-tag-moved", `${upstreamTag} resolves to ${tagged.stdout.trim() || "nothing"}, not the selected ${upstreamCommit}`);
    const source = join3(work, "source");
    cpSync(join3(inputs, "patches"), join3(source, "components", component, "patches"), { recursive: true });
    const miseExecutable = await (options.mise ?? installMise)(lock, join3(work, "mise"));
    const executor = {
      platform: PLATFORM,
      isolation: "hosted",
      async run(execution) {
        const env = { ...execution.env, PATH: [execution.env.PATH, ...SYSTEM_PATH].filter(Boolean).join(":") };
        const child = Bun.spawn(execution.argv, { cwd: execution.cwd, env, stdin: "ignore", stdout: "pipe", stderr: "pipe" });
        const [stdout, stderr, code] = await Promise.all([new Response(child.stdout).text(), new Response(child.stderr).text(), child.exited]);
        return { code, stdout, stderr };
      }
    };
    const tempRoot = mkdtempSync3(existsSync4("/tmp") ? "/tmp/hos-" : join3(tmpdir2(), "hos-"));
    return finish(await runBuild({
      component,
      sourceRoot: source,
      mirror,
      upstreamTag,
      upstreamCommit,
      series,
      build,
      manifest,
      miseLock: lock,
      platform: PLATFORM,
      workRoot: join3(work, "build"),
      tempRoot,
      snapshot: { path: snapshot, sha256: sha256(readFileSync3(snapshot)) },
      toolchain: { kind: "mise", miseExecutable },
      executor,
      git,
      progress: (event) => console.error(JSON.stringify(event))
    }));
  } catch (error) {
    if (error instanceof ManifestError)
      return refuse("fail", "manifest", error.message);
    const text = error instanceof Error ? error.message : String(error);
    const typed = /^(fail|unverified)\/([a-z-]+): (.*)$/s.exec(text);
    return typed ? refuse(typed[1], typed[2], typed[3]) : refuse("unverified", "build-wrapper", text);
  }
}
if (import.meta.main) {
  const env = (name) => process.env[name] ?? "";
  process.exitCode = await runHosted({
    inputs: "inputs",
    out: "out",
    work: join3(process.env.RUNNER_TEMP ?? tmpdir2(), "orca-build"),
    component: env("COMPONENT"),
    upstreamTag: env("UPSTREAM_TAG"),
    upstreamCommit: env("UPSTREAM_COMMIT"),
    series: env("SERIES"),
    build: env("BUILD")
  });
}
