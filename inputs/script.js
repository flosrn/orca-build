var lockSchema = object({ tools: record(string2(), array(object({ version: string2() }).catchall(unknown()))) });
function serializeLock(lock) {
  const tools = lock.tools;
  const lines = ["lockfile_version = 2"];
  for (const [tool, entries] of Object.entries(tools))
    for (const entry of entries) {
      lines.push(`[[tools.${JSON.stringify(tool)}]]`);
      const tomlValue = (value) => {
        if (Array.isArray(value))
          return `[${value.map(tomlValue).join(", ")}]`;
        if (value && typeof value === "object")
          return `{ ${Object.entries(value).map(([key, item]) => `${JSON.stringify(key)} = ${tomlValue(item)}`).join(", ")} }`;
        if (typeof value === "string" || typeof value === "boolean" || typeof value === "number" && Number.isFinite(value))
          return JSON.stringify(value);
        throw new Error("mise lock metadata is not representable as TOML");
      };
      for (const [key, value] of Object.entries(entry))
        lines.push(`${JSON.stringify(key)} = ${tomlValue(value)}`);
    }
  return `${lines.join(`
`)}
`;
}
function preparedToolchain(toolchain) {
  const invalid = (detail) => {
    throw new BuildProblem({ verdict: "unverified", reason: "build-wrapper", detail });
  };
  if (typeof toolchain.root !== "string" || !isAbsolute2(toolchain.root) || !Array.isArray(toolchain.paths) || !toolchain.paths.length)
    return invalid("prepared toolchain requires an absolute root and nonempty tool paths");
  try {
    const root = realpathSync2(toolchain.root);
    if (!statSync(root).isDirectory())
      return invalid("prepared toolchain root is not a directory");
    const paths = Array.from(toolchain.paths, (path) => {
      if (typeof path !== "string" || !isAbsolute2(path) || path.includes(delimiter) || path.includes("\x00"))
        return invalid("prepared tool paths must be absolute PATH directories");
      const real = realpathSync2(path);
      if (outside(root, real) || !statSync(real).isDirectory())
        return invalid("prepared tool path escaped its root or is not a directory");
      if (real.includes(delimiter))
        return invalid("prepared tool path cannot contain the PATH delimiter");
      return real;
    });
    return { kind: "prepared", root, paths };
  } catch (error) {
    if (error instanceof BuildProblem)
      throw error;
    return invalid(`prepared toolchain path is unavailable: ${error instanceof Error ? error.message : String(error)}`);
  }
}
